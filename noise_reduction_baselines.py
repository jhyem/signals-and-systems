@dataclass(frozen=True)
class Config:
    sample_rate: int = 16000
    n_fft: int = 512
    hop: int = 128
    filter_order: int = 4
    lowpass_hz: float = 3500.0
    highpass_hz: float = 100.0
    bandstop_hz: tuple = (950.0, 1050.0)
    basic_stages: tuple = ("highpass", "lowpass", "bandstop")
    noise_fraction: float = 0.20
    subtraction_alpha: float = 1.8
    subtraction_floor: float = 0.03
    wiener_smoothing: float = 0.98
    wiener_gain_floor: float = 0.05

    def __post_init__(self):
        if self.sample_rate != 16000:
            raise ValueError("This baseline uses 16000 Hz / wideband PESQ.")
        if not 0 < self.hop <= self.n_fft or self.n_fft < 4:
            raise ValueError("Require 0 < hop <= n_fft and n_fft >= 4.")
        if not signal.check_NOLA("hann", self.n_fft, self.n_fft - self.hop):
            raise ValueError("STFT window/hop does not satisfy NOLA.")
        if not 0 < self.noise_fraction <= 1:
            raise ValueError("noise_fraction must be in (0, 1].")
        if not 0 <= self.wiener_smoothing < 1:
            raise ValueError("wiener_smoothing must be in [0, 1).")
        if not 0 <= self.subtraction_floor <= 1 or self.subtraction_alpha < 0:
            raise ValueError("Invalid spectral subtraction parameters.")
        if not 0 <= self.wiener_gain_floor <= 1:
            raise ValueError("wiener_gain_floor must be in [0, 1].")
        nyquist = self.sample_rate / 2
        if not 0 < self.highpass_hz < self.lowpass_hz < nyquist:
            raise ValueError("Require 0 < highpass < lowpass < Nyquist.")
        if not 0 < self.bandstop_hz[0] < self.bandstop_hz[1] < nyquist:
            raise ValueError("Invalid band-stop interval.")
        if self.filter_order < 1 or int(self.filter_order) != self.filter_order:
            raise ValueError("filter_order must be a positive integer.")
        if any(s not in ("lowpass", "highpass", "bandstop") for s in self.basic_stages):
            raise ValueError("Unknown basic filter stage.")


