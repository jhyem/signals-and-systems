"""LP·HP·BS는 각각 독립적으로 실행하며, 아래쪽 HP → LP → BS는 추가 비교용 조합입니다.
Butterworth SOS 필터를 순방향·역방향으로 적용하는 오프라인 처리입니다.

대역은 `Config.highpass_hz`, `lowpass_hz`, `bandstop_hz`를 따릅니다. 차단 대역이 음성과 겹치면 음성도 감쇠됩니다.
양방향 처리의 크기 응답은 단방향 응답의 제곱이므로 설정 차단 주파수에서 약 −6 dB입니다.

"""

def basic_filter(noisy, kind="combined", cfg=CFG):
    """Butterworth SOS, forward/backward filtering (offline, zero phase)."""
    y = waveform(noisy).copy()
    stages = cfg.basic_stages if kind == "combined" else (kind,)
    cutoffs = {"lowpass": cfg.lowpass_hz, "highpass": cfg.highpass_hz,
               "bandstop": cfg.bandstop_hz}
    for stage in stages:
        if stage not in cutoffs:
            raise ValueError(f"Unknown filter: {stage}")
        sos = signal.butter(cfg.filter_order, cutoffs[stage], btype=stage,
                            fs=cfg.sample_rate, output="sos")
        # The usual padding, bounded for very short input signals.
        ntaps = 2 * len(sos) + 1 - min((sos[:, 2] == 0).sum(), (sos[:, 5] == 0).sum())
        y = signal.sosfiltfilt(sos, y, padlen=min(3 * int(ntaps), len(y) - 1))
    return y

"""### 4. 공통 STFT와 잡음 추정

Hann 창(512 samples), hop 128 samples로 STFT를 계산합니다.
경계 padding을 제외한 완전한 프레임 중 저에너지 20%의 평균 파워를 3-bin 평활화하여 잡음 PSD를 추정합니다.
잡음 PSD는 파일별로 고정하며 clean은 사용하지 않습니다. 무음 검출기는 아니므로 연속 발화·변동 잡음에서는 추정 오차가 생길 수 있습니다.

"""

def stft_audio(x, cfg=CFG):
    x = waveform(x)
    if x.size < cfg.n_fft:
        x = np.pad(x, (0, cfg.n_fft - x.size))
    return signal.stft(x, fs=cfg.sample_rate, window="hann", nperseg=cfg.n_fft,
                       noverlap=cfg.n_fft - cfg.hop, nfft=cfg.n_fft,
                       boundary="zeros", padded=True)


def inverse_stft(z, length, cfg=CFG):
    _, y = signal.istft(z, fs=cfg.sample_rate, window="hann", nperseg=cfg.n_fft,
                        noverlap=cfg.n_fft - cfg.hop, nfft=cfg.n_fft,
                        input_onesided=True, boundary=True)
    if len(y) < length:
        raise ValueError("Inverse STFT produced insufficient samples.")
    return waveform(y[:length])


def estimate_noise_power(z, times, length, cfg=CFG):
    """Average the lowest-energy complete frames; no clean/reference access."""
    power = np.abs(z) ** 2
    # Avoid selecting artificially quiet frames introduced by boundary padding.
    centers = np.rint(times * cfg.sample_rate).astype(int)
    full = np.flatnonzero((centers >= cfg.n_fft // 2) &
                          (centers + cfg.n_fft // 2 <= length))
    if not len(full):
        full = np.arange(power.shape[1])
    energy = power[:, full].mean(axis=0)
    count = max(1, int(np.ceil(cfg.noise_fraction * len(full))))
    selected = full[np.argsort(energy, kind="stable")[:count]]
    estimate = power[:, selected].mean(axis=1)
    return np.maximum(uniform_filter1d(estimate, size=3, mode="nearest"), 1e-18)

