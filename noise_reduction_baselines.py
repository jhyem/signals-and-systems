def load_manifest(root, split):
    if split not in ("train", "validation"):
        raise ValueError("split must be train or validation")
    root = Path(root).resolve()
    df = pd.read_csv(root / split / "samples.csv")
    required = {"segment_id", "clean_path", "noisy_path", "sample_rate_hz", "num_samples",
                "noise_category", "noise_collection", "noise_code", "noise_difficulty",
                "target_snr_db", "split"}
    if not required.issubset(df.columns) or df.empty:
        raise ValueError("Empty manifest or required columns missing.")
    if df.segment_id.duplicated().any():
        raise ValueError("Duplicate segment IDs.")
    if "split" in df and not df["split"].eq(split).all():
        raise ValueError("Manifest split mismatch.")
    for column in ("clean_path", "noisy_path"):
        for relative in df[column]:
            path = (root / relative).resolve()
            if not path.is_relative_to(root) or not path.is_file():
                raise FileNotFoundError(f"Invalid/missing file: {path}")
    return df


def read_audio(root, row, kind, cfg=CFG):
    x, sr = sf.read(Path(root) / row[f"{kind}_path"], dtype="float64")
    x = waveform(x)
    if sr != cfg.sample_rate or sr != int(row["sample_rate_hz"]):
        raise ValueError(f"Sample-rate mismatch for {row['segment_id']}: {sr}")
    if x.size != int(row["num_samples"]):
        raise ValueError(f"Length mismatch for {row['segment_id']}")
    return x


def read_pair(root, row, cfg=CFG):
    return read_audio(root, row, "clean", cfg), read_audio(root, row, "noisy", cfg)


def read_audio_file(path, cfg=CFG, data_root=None):
    """Read exactly one file; relative paths use data_root, or the working folder."""
    path = Path(path).expanduser()
    if not path.is_absolute() and data_root is not None:
        path = Path(data_root) / path
    path = path.resolve()
    x, sample_rate = sf.read(path, dtype="float64")
    if sample_rate != cfg.sample_rate:
        raise ValueError(f"Expected {cfg.sample_rate} Hz, got {sample_rate} Hz: {path}")
    return waveform(x), path




