def show_example(noisy_path, clean_path=None, cfg=CFG, data_root=None,
                 include_basic_variants=True, verbose=True):
    """Infer and display one input file. clean_path is optional and comparison-only."""
    import matplotlib.pyplot as plt
    from IPython.display import Audio, Markdown, display

    from time import perf_counter
    started = perf_counter()
    if verbose:
        print("[1/3] Reading audio and running filters...", flush=True)
    outputs = infer_file(noisy_path, cfg, data_root, include_basic_variants)
    noisy = outputs["noisy_input"]
    if clean_path is not None:
        clean, _ = read_audio_file(clean_path, cfg, data_root)
        if clean.shape != noisy.shape:
            raise ValueError("Clean and noisy files must have the same length.")
        outputs = {"clean_reference": clean, **outputs}
    if verbose:
        print(f"[2/3] Building spectrograms ({perf_counter() - started:.2f}s)...", flush=True)
    label = Path(noisy_path).name
    reference_magnitude = max(float(np.abs(stft_audio(noisy, cfg)[2]).max()), 1e-12)
    fig, axes = plt.subplots(len(outputs), 1, figsize=(12, 2.15 * len(outputs)),
                             sharex=True, sharey=True, constrained_layout=True)
    for ax, (name, y) in zip(axes, outputs.items()):
        frequencies, times, z = stft_audio(y, cfg)
        db = 20 * np.log10(np.maximum(np.abs(z), 1e-12) / reference_magnitude)
        mesh = ax.pcolormesh(times, frequencies / 1000, db, shading="auto",
                             cmap="magma", vmin=-80, vmax=0)
        ax.set(title=name, ylabel="Frequency (kHz)")
    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"{label} | shared dB reference: noisy peak")
    fig.colorbar(mesh, ax=list(axes), label="dB relative to noisy STFT peak")
    # Publish directly: GUI backends can block in plt.show().
    try:
        display(fig)
    finally:
        plt.close(fig)
    if verbose:
        print(f"[3/3] Building audio players ({perf_counter() - started:.2f}s)...", flush=True)
    # A single playback gain preserves level differences across all methods.
    playback_gain = 0.99 / max(1.0, max(float(np.abs(y).max()) for y in outputs.values()))
    display(Markdown(f"**{label}** — 공통 재생 gain: {playback_gain:.4f}"))
    for name, y in outputs.items():
        display(Markdown(f"**{name}**"))
        display(Audio(y * playback_gain, rate=cfg.sample_rate, normalize=False))
    if verbose:
        print(f"Done ({perf_counter() - started:.2f}s).", flush=True)
    return outputs

"""### 8. 전체 샘플 테스트 함수

`test_all_samples(DATA_ROOT, split="validation", cfg=CFG)`는 manifest 전체를 평가합니다.
`split="train"` 또는 `"all"`도 가능하며, `all`은 split별로 집계합니다.

$\mathrm{SNR}=10\log_{10}(\sum s[n]^2/\sum(s[n]-\hat{s}[n])^2)$, PESQ는 16 kHz wideband입니다.
정규화·시간 정렬 없이 파일별 점수를 평균하며, PESQ 실패는 원인과 개수를 별도 기록합니다.

"""

def snr_db(clean, estimate):
    clean, estimate = waveform(clean), waveform(estimate)
    if clean.shape != estimate.shape:
        raise ValueError("SNR requires equal lengths.")
    energy = np.sum(clean ** 2)
    if energy <= 0:
        raise ValueError("SNR is undefined for a silent reference.")
    error = np.sum((clean - estimate) ** 2)
    return float(np.inf if error == 0 else 10 * np.log10(energy / error))


def pesq_score(clean, estimate, sample_rate=16000):
    from pesq import pesq, PesqError
    try:
        value = float(pesq(sample_rate, clean, estimate, mode="wb",
                           on_error=PesqError.RAISE_EXCEPTION))
        if not np.isfinite(value) or value < 0:
            raise ValueError(f"Invalid PESQ return value: {value}")
        return value, ""
    except (PesqError, ValueError) as error:
        return np.nan, f"{type(error).__name__}: {error}"


def summarize_scores(detail, group_columns=("method",)):
    summary = detail.groupby(list(group_columns), dropna=False, sort=False).agg(
        n_total=("segment_id", "size"),
        snr_mean_db=("snr_db", "mean"), snr_std_db=("snr_db", "std"),
        delta_snr_mean_db=("delta_snr_db", "mean"),
        pesq_mean=("pesq", "mean"), pesq_std=("pesq", "std"),
        pesq_valid=("pesq", "count"),
        delta_pesq_mean=("delta_pesq", "mean"),
        delta_pesq_valid=("delta_pesq", "count"),
    ).reset_index()
    summary["pesq_failed"] = summary.n_total - summary.pesq_valid
    return summary


def evaluate_dataset(root, manifest, output_dir, cfg=CFG, include_basic_variants=True,
                     split="validation"):
    # Fail before processing if PESQ is not installed; never silently omit the metric.
    import pesq  # noqa: F401
    if split not in ("train", "validation"):
        raise ValueError("split must be train or validation")
    if "split" in manifest and not manifest["split"].eq(split).all():
        raise ValueError(f"Evaluation expects the {split} split.")
    if manifest.empty or manifest.segment_id.duplicated().any():
        raise ValueError("Empty or duplicate evaluation manifest.")
    rows = []
    for _, row in tqdm(manifest.iterrows(), total=len(manifest), desc=f"Evaluate {split}"):
        clean, noisy = read_pair(root, row, cfg)
        outputs = {"noisy_input": noisy, **enhance(noisy, cfg, include_basic_variants)}
        # Evaluate the same valid region for all methods; infer on the full waveform.
        valid = int(row.get("valid_samples", len(clean)))
        if not 0 < valid <= len(clean):
            raise ValueError(f"Invalid valid_samples: {row['segment_id']}")
        clean = clean[:valid]
        input_snr = snr_db(clean, noisy[:valid])
        input_pesq, input_error = pesq_score(clean, noisy[:valid], cfg.sample_rate)
        for method, y in outputs.items():
            score_snr = snr_db(clean, y[:valid])
            score_pesq, error = ((input_pesq, input_error) if method == "noisy_input"
                                 else pesq_score(clean, y[:valid], cfg.sample_rate))
            rows.append({"split": split, "segment_id": row["segment_id"], "method": method,
                         "noise_category": row.get("noise_category", "unknown"),
                         "noise_difficulty": row.get("noise_difficulty", "unknown"),
                         "target_snr_db": row.get("target_snr_db", np.nan),
                         "snr_db": score_snr, "delta_snr_db": score_snr - input_snr,
                         "pesq": score_pesq, "delta_pesq": score_pesq - input_pesq,
                         "pesq_error": error})
    detail = pd.DataFrame(rows)
    summary = summarize_scores(detail)
    # Common successful subset for fair PESQ comparisons if a method has failures.
    complete = detail.groupby("segment_id").pesq.apply(lambda x: x.notna().all())
    common = detail[detail.segment_id.isin(complete[complete].index)]
    common_summary = summarize_scores(common)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    detail.to_csv(output_dir / f"{split}_per_file.csv", index=False, encoding="utf-8-sig")
    summary.to_csv(output_dir / f"{split}_summary.csv", index=False, encoding="utf-8-sig")
    common_summary.to_csv(output_dir / f"{split}_common_subset.csv", index=False,
                          encoding="utf-8-sig")
    for group in ("noise_category", "noise_difficulty", "target_snr_db"):
        summarize_scores(detail, ("method", group)).to_csv(
            output_dir / f"{split}_by_{group}.csv", index=False, encoding="utf-8-sig")
    versions = {name: importlib.metadata.version(name) for name in
                ("numpy", "scipy", "soundfile", "pandas", "pesq")}
    metadata = {"config": asdict(cfg), "python": platform.python_version(),
                "versions": versions, "split": split, "evaluated_files": len(manifest),
                "methods": detail.method.unique().tolist(), "pesq_mode": "wb",
                "common_pesq_files": int(complete.sum()),
                "snr": "10*log10(sum(clean**2)/sum((clean-output)**2)); no level alignment",
                "aggregation": "unweighted arithmetic mean across files"}
    (output_dir / "run_config.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    if summary.pesq_failed.sum():
        print("PESQ failures detected: inspect pesq_error and compare the common-subset table.")
    return detail, summary




def test_all_samples(root, split="validation", output_dir=None, cfg=CFG,
                     include_basic_variants=True):
    """Reload and evaluate EVERY file of a split, independently of example filters.

    split='all' evaluates train and validation and returns their combined tables.
    No plots or playback widgets are created here.
    """
    if split not in ("train", "validation", "all"):
        raise ValueError("split must be train, validation or all")
    root = Path(root).resolve()
    output_dir = Path(output_dir) if output_dir is not None else root / "outputs" / "evaluation"
    splits = ("train", "validation") if split == "all" else (split,)
    details = []
    for name in splits:
        full_manifest = load_manifest(root, name)
        destination = output_dir / name if split == "all" else output_dir
        detail, summary = evaluate_dataset(root, full_manifest, destination, cfg,
                                            include_basic_variants, split=name)
        if not detail.groupby("method").size().eq(len(full_manifest)).all():
            raise RuntimeError("Not every manifest entry was evaluated.")
        details.append(detail)
    if split != "all":
        return details[0], summary
    combined = pd.concat(details, ignore_index=True)
    summary = summarize_scores(combined, ("split", "method"))
    combined.to_csv(output_dir / "all_per_file.csv", index=False, encoding="utf-8-sig")
    summary.to_csv(output_dir / "all_summary.csv", index=False, encoding="utf-8-sig")
    return combined, summary

"""### 9. 전체 데이터 처리 결과 저장 함수

`export_enhanced(...)`는 noisy 파일을 처리하여 `outputs/enhanced/<split>/<method>/`에 FLOAT WAV를 저장합니다.
표본률과 길이를 유지하며 정규화하지 않습니다.

"""

def export_enhanced(root, manifest, split, output_dir, cfg=CFG):
    if split not in ("train", "validation"):
        raise ValueError("split must be train or validation")
    if "split" in manifest and not manifest["split"].eq(split).all():
        raise ValueError("Manifest split mismatch.")
    destination = Path(output_dir).resolve()
    source = Path(root).resolve()
    for source_split in ("train", "validation"):
        if destination == source / source_split or destination.is_relative_to(source / source_split):
            raise ValueError("Choose an output folder outside the original audio splits.")
    records = []
    for _, row in tqdm(manifest.iterrows(), total=len(manifest), desc=f"Export {split}"):
        noisy = read_audio(root, row, "noisy", cfg)
        for method, y in enhance(noisy, cfg).items():
            target = destination / split / method / Path(row["noisy_path"]).name
            target.parent.mkdir(parents=True, exist_ok=True)
            # FLOAT WAV preserves output amplitude without clipping or normalizing.
            sf.write(target, y, cfg.sample_rate, subtype="FLOAT")
            records.append({"segment_id": row["segment_id"], "method": method,
                            "output_path": str(target), "peak": float(np.abs(y).max())})
    exported = pd.DataFrame(records)
    destination.mkdir(parents=True, exist_ok=True)
    exported.to_csv(destination / f"{split}_outputs.csv", index=False, encoding="utf-8-sig")
    (destination / "config.json").write_text(json.dumps(asdict(cfg), indent=2), encoding="utf-8")
    return exported

