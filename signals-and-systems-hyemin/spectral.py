"""Spectral Subtraction speech enhancement for the Signals and Systems challenge.

Derived from the team's original noise_reduction_baselines.ipynb implementation.
Changes for this candidate (Team Member B):
  - Over-subtraction factor (alpha): 1.8
  - Spectral floor: 0.03
  - Standalone `enhance(noisy, sample_rate=16000)` interface
  - Accepts mono 1D array or 2D (samples, channels) waveform, preserving shape

No clean/reference audio or validation metadata is used during enhancement.
Requires NumPy and SciPy. Does not require Colab, PESQ, or dataset files.
"""

import numpy as np
from scipy import signal
from scipy.ndimage import uniform_filter1d

# 공통 및 실험 파라미터 정의
N_FFT = 512
HOP = 128
NOISE_FRACTION = 0.20
SUBTRACTION_ALPHA = 1.8
SUBTRACTION_FLOOR = 0.03


def _waveform(x):
    """모노 파형 검증 및 정수/실수 정규화 (베이스라인과 동일한 정밀도 유지)."""
    x = np.asarray(x, dtype=np.float64)
    if x.ndim != 1 or x.size == 0 or not np.isfinite(x).all():
        raise ValueError("Expected a nonempty, finite mono waveform.")
    return x


def _stft_audio(x, sample_rate):
    x = _waveform(x)
    if x.size < N_FFT:
        x = np.pad(x, (0, N_FFT - x.size))
    return signal.stft(
        x,
        fs=sample_rate,
        window="hann",
        nperseg=N_FFT,
        noverlap=N_FFT - HOP,
        nfft=N_FFT,
        boundary="zeros",
        padded=True,
    )


def _inverse_stft(z, length, sample_rate):
    _, y = signal.istft(
        z,
        fs=sample_rate,
        window="hann",
        nperseg=N_FFT,
        noverlap=N_FFT - HOP,
        nfft=N_FFT,
        input_onesided=True,
        boundary=True,
    )
    if len(y) < length:
        raise ValueError("Inverse STFT produced insufficient samples.")
    return _waveform(y[:length])


def _estimate_noise_power(z, times, length, sample_rate):
    """저에너지 프레임을 활용한 고정 잡음 PSD 추정 (정답 데이터 미사용)."""
    power = np.abs(z) ** 2
    centers = np.rint(times * sample_rate).astype(int)
    full = np.flatnonzero(
        (centers >= N_FFT // 2) & (centers + N_FFT // 2 <= length)
    )
    if not len(full):
        full = np.arange(power.shape[1])
    energy = power[:, full].mean(axis=0)
    count = max(1, int(np.ceil(NOISE_FRACTION * len(full))))
    selected = full[np.argsort(energy, kind="stable")[:count]]
    estimate = power[:, selected].mean(axis=1)
    return np.maximum(uniform_filter1d(estimate, size=3, mode="nearest"), 1e-18)


def _enhance_mono(noisy, sample_rate):
    x = _waveform(noisy)
    _, times, z = _stft_audio(x, sample_rate)
    power = np.abs(z) ** 2
    noise = _estimate_noise_power(z, times, len(x), sample_rate)[:, None]

    # Spectral Subtraction 핵심 연산 (Alpha: 1.8, Floor: 0.03 적용)
    target = np.maximum(
        power - SUBTRACTION_ALPHA * noise,
        SUBTRACTION_FLOOR * power
    )
    gain = np.sqrt(np.clip(target / np.maximum(power, 1e-18), 0, 1))

    return _inverse_stft(gain * z, len(x), sample_rate)


def enhance(noisy, sample_rate=16000):
    """입력 신호에서 잡음을 제거하고 입력과 동일한 형태의 파형을 반환합니다.

    Args:
        noisy: 1D 모노 배열 또는 (samples, channels) 2D 배열 (예: soundfile.read 결과).
        sample_rate: 샘플링 주파수 (본 챌린지는 16,000 Hz 사용).

    Returns:
        잡음이 제거된 float64 NumPy 배열 (원래 입력 shape 유지).
    """
    if sample_rate != 16000:
        raise ValueError("This challenge baseline supports 16,000 Hz only.")
    samples = np.asarray(noisy)
    if samples.ndim == 1:
        return _enhance_mono(samples, sample_rate)
    if samples.ndim == 2 and samples.shape[0] > 0 and samples.shape[1] > 0:
        return np.column_stack([
            _enhance_mono(samples[:, ch], sample_rate)
            for ch in range(samples.shape[1])
        ])
    raise ValueError("Expected a 1D mono or 2D (samples, channels) audio array.")